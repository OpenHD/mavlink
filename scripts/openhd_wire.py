#!/usr/bin/env python3
"""Generate small wire descriptors from the same XML used by mavgen.

No payload layout or CRC is maintained here. Includes and MAVLink field sorting
are resolved by the pinned pymavlink parser.
"""
import argparse
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "pymavlink"))
from generator import mavparse


def descriptors():
    seen, messages = set(), {}
    def visit(path):
        path = path.resolve()
        if path in seen:
            return
        seen.add(path)
        xml = mavparse.MAVXML(str(path), wire_protocol_version="2.0")
        for include in xml.include:
            visit(path.parent / include)
        for msg in xml.message:
            if msg.id in messages:
                raise ValueError(f"Duplicate message ID {msg.id}")
            messages[msg.id] = dict(name=msg.name, crc=msg.crc_extra,
                length=msg.wire_length, minimumLength=msg.wire_min_length,
                fields={f.name: f.wire_offset for f in msg.ordered_fields})
    visit(ROOT / "message_definitions/v1.0/openhd.xml")
    return dict(sorted(messages.items()))


def products():
    messages = descriptors()
    banner = "// Generated by OpenHD/mavlink scripts/openhd_wire.py; do not edit.\n"
    ts = banner + "export const mavlinkCrcExtras = new Map<number, number>([\n"
    ts += "".join(f"  [{i}, {m['crc']}], // {m['name']}\n" for i, m in messages.items()) + "]);\n"
    ts += 'export const mavlinkWire = ' + json.dumps({m['name']: dict(id=i, **m) for i, m in messages.items()}, indent=2) + ' as const;\n'
    cs = banner + "namespace OpenHdWebUi.Server.Services.Settings;\ninternal static class MavlinkWire\n{\n"
    cs += "    internal static readonly System.Collections.Generic.Dictionary<int, byte> CrcExtras = new()\n    {\n"
    cs += "".join(f"        [{i}] = {m['crc']}, // {m['name']}\n" for i, m in messages.items()) + "    };\n"
    for i, m in messages.items():
        if m['name'] == 'FILE_TRANSFER_PROTOCOL' or m['name'].startswith('PARAM_EXT_'):
            cs += f"    internal static class {m['name']} {{\n        internal const int Id = {i}, Length = {m['length']};\n"
            cs += ''.join(f"        internal const int @{f} = {offset};\n" for f, offset in m['fields'].items()) + '    }\n'
    cs += '}\n'
    cpp = banner + "#pragma once\n#include <cstdint>\n#include <optional>\nnamespace glide::openhd::generated {\n"
    cpp += "inline std::optional<std::uint8_t> crc_extra(std::uint32_t id) {\n    switch (id) {\n"
    cpp += "".join(f"    case {i}: return {m['crc']}; // {m['name']}\n" for i, m in messages.items()) + "    default: return std::nullopt;\n    }\n}\n"
    for i, m in messages.items():
        cpp += f"namespace {m['name'].lower()} {{\ninline constexpr std::uint32_t id = {i};\nnamespace fields {{\n"
        cpp += "".join(f"inline constexpr unsigned {f} = {offset};\n" for f, offset in m['fields'].items()) + "}\n}\n"
    cpp += "}\n"
    return {"wire.json": json.dumps(messages, indent=2) + "\n", "mavlink-wire.ts": ts,
            "MavlinkWire.g.cs": cs, "mavlink_wire.hpp": cpp}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=pathlib.Path, required=True)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for name, content in products().items():
        path = args.output / name
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f"Stale generated file: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
